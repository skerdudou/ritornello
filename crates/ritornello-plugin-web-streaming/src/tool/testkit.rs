//! Test-only helpers: keys generated for the test (never a real one), signed
//! lists of sums, fake yt-dlp packages, and a fetcher that serves from memory.

use std::collections::HashMap;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::sync::{Mutex, OnceLock};

use pgp::composed::{DetachedSignature, KeyType, SecretKeyParamsBuilder, SignedPublicKey, SignedSecretKey};
use pgp::crypto::hash::HashAlgorithm;
use pgp::ser::Serialize;
use pgp::types::Password;
use rand::SeedableRng;

use super::fetch::{BoxFuture, Fetch, Limit};

/// An RSA key like yt-dlp's (but 2048 bits): RSA, unlike EdDSA, still
/// verifies a SHA-1 signature, which is what refusing broken hashes is for.
pub fn rsa_key() -> &'static SignedSecretKey {
    static KEY: OnceLock<SignedSecretKey> = OnceLock::new();
    KEY.get_or_init(|| generate_typed(KeyType::Rsa(2048), 4, "Test RSA key <rsa@invalid>"))
}

fn generate(seed: u64, uid: &str) -> SignedSecretKey {
    generate_typed(KeyType::Ed25519Legacy, seed, uid)
}

fn generate_typed(key_type: KeyType, seed: u64, uid: &str) -> SignedSecretKey {
    let params = SecretKeyParamsBuilder::default()
        .key_type(key_type)
        .can_certify(true)
        .can_sign(true)
        .primary_user_id(uid.into())
        .build()
        .unwrap();
    params.generate(rand::rngs::StdRng::seed_from_u64(seed)).unwrap()
}

/// The key the tests' releases are signed with.
pub fn test_key() -> &'static SignedSecretKey {
    static KEY: OnceLock<SignedSecretKey> = OnceLock::new();
    KEY.get_or_init(|| generate(1, "Test release key <test@invalid>"))
}

/// Another key: a signature by it is a bad signature.
pub fn other_key() -> &'static SignedSecretKey {
    static KEY: OnceLock<SignedSecretKey> = OnceLock::new();
    KEY.get_or_init(|| generate(2, "Someone else <else@invalid>"))
}

pub fn public(key: &SignedSecretKey) -> SignedPublicKey {
    key.to_public_key()
}

/// A binary detached signature of `data`, as yt-dlp publishes them.
pub fn sign_with(key: &SignedSecretKey, hash: HashAlgorithm, data: &[u8]) -> Vec<u8> {
    let sig = DetachedSignature::sign_binary_data(
        rand::rngs::StdRng::seed_from_u64(3),
        &key.primary_key,
        &Password::empty(),
        hash,
        data,
    )
    .unwrap();
    sig.to_bytes().unwrap()
}

pub fn sign(data: &[u8]) -> Vec<u8> {
    sign_with(test_key(), HashAlgorithm::Sha512, data)
}

pub fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// A list of sums in the GNU format yt-dlp publishes.
pub fn sums_for(entries: &[(&str, &[u8])]) -> Vec<u8> {
    entries.iter().map(|(name, bytes)| format!("{}  {name}\n", hex(&super::verify::sha256(bytes)))).collect::<String>().into_bytes()
}

/// A zip of `files`, behind a shebang line like the real zipapp.
pub fn zipapp(files: &[(&str, &str)]) -> Vec<u8> {
    zipapp_with(files, zip::CompressionMethod::Deflated)
}

/// The same, with the files stored as they are (so a test can find and
/// damage their bytes).
pub fn zipapp_with(files: &[(&str, &str)], method: zip::CompressionMethod) -> Vec<u8> {
    let mut out = std::io::Cursor::new(Vec::new());
    {
        let mut w = zip::ZipWriter::new(&mut out);
        let opts = zip::write::SimpleFileOptions::default().compression_method(method);
        for (name, text) in files {
            w.start_file(*name, opts).unwrap();
            w.write_all(text.as_bytes()).unwrap();
        }
        w.finish().unwrap();
    }
    let mut bytes = b"#!/usr/bin/env python3\n".to_vec();
    bytes.extend(out.into_inner());
    bytes
}

/// A `yt_dlp` package that answers `--version` with `version` (and says it
/// in `yt_dlp/version.py`, as the real one does), and fails to start when
/// `version` is empty (its `version.py` then says 9999.1.1).
pub fn fake_package(version: &str) -> Vec<(&'static str, String)> {
    let init = if version.is_empty() {
        "def main(argv=None):\n    raise SystemExit(1)\n".to_string()
    } else {
        format!(
            "import sys\n\ndef main(argv=None):\n    argv = list(sys.argv[1:] if argv is None else argv)\n    if '--version' in argv:\n        print({version:?})\n    raise SystemExit(0)\n"
        )
    };
    let declared = if version.is_empty() { "9999.1.1" } else { version };
    vec![
        ("__main__.py", "import yt_dlp\nyt_dlp.main()\n".to_string()),
        ("yt_dlp/__init__.py", init),
        ("yt_dlp/version.py", format!("# Autogenerated by devscripts/update-version.py\n\n__version__ = '{declared}'\n\nRELEASE_GIT_HEAD = 'abc'\n")),
        ("yt_dlp/extractor/__init__.py", "# extractors\n".to_string()),
    ]
}

pub fn fake_zipapp(version: &str) -> Vec<u8> {
    let files = fake_package(version);
    let refs: Vec<(&str, &str)> = files.iter().map(|(n, t)| (*n, t.as_str())).collect();
    zipapp(&refs)
}

/// Serves fixed answers per URL and remembers what was asked.
#[derive(Default)]
pub struct FakeFetch {
    pub answers: Mutex<HashMap<String, Result<Vec<u8>, String>>>,
    pub asked: Mutex<Vec<String>>,
}

impl FakeFetch {
    pub fn serve(&self, url: &str, answer: Result<Vec<u8>, String>) {
        self.answers.lock().unwrap().insert(url.to_string(), answer);
    }

    pub fn asked(&self) -> Vec<String> {
        self.asked.lock().unwrap().clone()
    }

    pub fn forget(&self) {
        self.asked.lock().unwrap().clear();
    }
}

impl Fetch for FakeFetch {
    fn get(&self, url: &str, limit: Limit) -> BoxFuture<Result<Vec<u8>, String>> {
        self.asked.lock().unwrap().push(url.to_string());
        let answer = self.answers.lock().unwrap().get(url).cloned().unwrap_or_else(|| Err(format!("404 {url}")));
        let answer = answer.and_then(|b| if b.len() > limit.max_bytes { Err("too big".into()) } else { Ok(b) });
        Box::pin(async move { answer })
    }

    /// The location served for `url` (as bytes, through [`serve`](Self::serve)).
    fn redirect_of(&self, url: &str, _deadline: std::time::Duration) -> BoxFuture<Result<String, String>> {
        self.asked.lock().unwrap().push(url.to_string());
        let answer = self.answers.lock().unwrap().get(url).cloned().unwrap_or_else(|| Err(format!("404 {url}")));
        Box::pin(async move { answer.map(|b| String::from_utf8(b).unwrap()) })
    }
}

/// A directory holding only a link to the real `python3`: the tests' search
/// path, so that what else the machine has installed (a node, a deno) never
/// changes what they see.
pub fn python_only_path() -> (tempfile::TempDir, PathBuf) {
    let dir = tempfile::tempdir().unwrap();
    let python = real_python3();
    std::os::unix::fs::symlink(&python, dir.path().join("python3")).unwrap();
    let p = dir.path().to_path_buf();
    (dir, p)
}

pub fn real_python3() -> PathBuf {
    let path = std::env::var_os("PATH").unwrap_or_default();
    std::env::split_paths(&path)
        .map(|d| d.join("python3"))
        .find(|p| p.is_file())
        .expect("python3 is needed by these tests (the plugin's one prerequisite): install it")
}

/// Runs `cmd`, retrying "text file busy": a script written an instant ago
/// may still be open for writing in a child another test thread forked
/// before its exec (the same reason `spawn_in_own_group` retries).
pub fn retrying<T>(mut run: impl FnMut() -> std::io::Result<T>) -> T {
    for _ in 0..80 {
        match run() {
            Err(e) if e.raw_os_error() == Some(libc::ETXTBSY) => std::thread::sleep(std::time::Duration::from_millis(25)),
            other => return other.unwrap(),
        }
    }
    panic!("text file busy for two seconds");
}

pub fn write_script(dir: &Path, name: &str, body: &str) -> PathBuf {
    use std::os::unix::fs::PermissionsExt;
    let p = dir.join(name);
    std::fs::write(&p, format!("#!/bin/sh\n{body}\n")).unwrap();
    std::fs::set_permissions(&p, std::fs::Permissions::from_mode(0o755)).unwrap();
    p
}
